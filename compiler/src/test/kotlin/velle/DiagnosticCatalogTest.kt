package velle

import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * The catalogue of what the compiler says (`wiki/diagnostics.md`), generated
 * from the refused specs under `src/test/resources/diagnostics/`. Each file
 * is named `<check>-<slug>.velle` and opens with `--` comment lines saying
 * what it spells; the table holds that description and every message of
 * that check the spec draws. The checked-in page is the test: a message
 * that changes fails here until the page is regenerated with
 * `VELLE_UPDATE_DIAGNOSTICS=true ./gradlew :compiler:test --tests velle.DiagnosticCatalogTest`
 * and the diff is reviewed.
 */
class DiagnosticCatalogTest {

    private val specs = File("src/test/resources/diagnostics")
    private val page = File("../wiki/diagnostics.md")

    private data class Row(val check: String, val spelling: String, val messages: List<String>)

    private fun checkNumber(check: String) = check.drop(1).toInt()

    private fun rowOf(file: File): Row {
        val check = file.name.substringBefore("-")
        val lines = file.readLines()
        val spelling = lines.takeWhile { line -> line.startsWith("--") }
            .joinToString(" ") { line -> line.removePrefix("--").trim() }
        val messages = Validator.validate(file.readText())
            .filter { diagnostic -> diagnostic.code == check }
            .map { diagnostic -> diagnostic.message }
        assertTrue(messages.isNotEmpty(), "${file.name} draws no $check: ${Validator.validate(file.readText())}")
        return Row(check, spelling, messages)
    }

    private fun render(rows: List<Row>): String {
        val text = StringBuilder()
        text.append("# What the compiler says\n\n")
        text.append("Every message the compiler prints for a refused spelling, one row per spelling. ")
        text.append("The check column is the entry in [checks.md](checks). ")
        text.append("The page is generated by `DiagnosticCatalogTest` from the specs under ")
        text.append("`compiler/src/test/resources/diagnostics/`, and that test fails when a message changes ")
        text.append("until the page is regenerated and the change reviewed.\n\n")
        text.append("| Check | The spelling | What the compiler says |\n|---|---|---|\n")
        for (row in rows) {
            val said = row.messages.joinToString("<br><br>") { message -> "`[${row.check}] ${cell(message)}`" }
            text.append("| ${row.check} | ${cell(row.spelling)} | $said |\n")
        }
        return text.toString()
    }

    private fun cell(text: String) = text.replace("|", "\\|").replace("\n", " ")

    @Test
    fun `the page lists what every catalogued spec draws`() {
        val rows = specs.listFiles { file -> file.extension == "velle" }!!
            .sortedWith(compareBy({ file -> checkNumber(file.name.substringBefore("-")) }, { file -> file.name }))
            .map(::rowOf)
        val expected = render(rows)
        if (System.getenv("VELLE_UPDATE_DIAGNOSTICS") == "true") {
            page.writeText(expected)
            return
        }
        assertEquals(expected, page.takeIf { it.exists() }?.readText(),
            "wiki/diagnostics.md is out of date; regenerate it with VELLE_UPDATE_DIAGNOSTICS=true and review the diff")
    }
}
