package velle

import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * The declarations `velle describe` has no words for, across every example spec, pinned in
 * `src/test/resources/describe/without-words.md`. Each is shown to the reader as Velle, and each
 * is a gap in the words of [Sentences], [RuleSentences], and [DeclarationSentences].
 *
 * When a form gains words, or an example gains a form without them, this test fails until the
 * list is regenerated with
 * `VELLE_UPDATE_WITHOUT_WORDS=true ./gradlew :compiler:test --tests velle.DescribeCoverageTest`
 * and the diff is reviewed.
 */
class DescribeCoverageTest {

    private val examples = File("../examples")
    private val pinned = File("src/test/resources/describe/without-words.md")

    private fun exampleSpecs(): List<File> = examples.listFiles { directory -> directory.isDirectory }!!
        .flatMap { directory -> directory.listFiles { file -> file.extension == "velle" }!!.toList() }
        .sortedBy { file -> file.path }

    /** One part of an example spec that describe shows as Velle: where it is, and the form that has no words. */
    private data class WithoutWords(val line: Int, val form: String, val writtenAs: String)

    /** The parts of one example that describe shows as Velle. */
    private fun withoutWords(spec: File): List<WithoutWords> {
        val path = "examples/${spec.parentFile.name}/${spec.name}"
        val diagnostics = Validator.validate(spec.readText())
        assertEquals(emptyList(), diagnostics, "$path validates")
        val description = SpecDescription.of(SpecVersion(path, spec.readText()))
        return description.declarations.flatMap { declaration -> declaration.unsaid }
            .map { part -> WithoutWords(part.line, part.form, part.writtenAs) }
    }

    private fun rendered(withoutWordsBySpec: List<Pair<File, List<WithoutWords>>>): String = buildString {
        appendLine("# What `velle describe` has no words for in the examples")
        appendLine()
        appendLine("Every part of an example spec that `velle describe` shows as Velle, because the compiler")
        appendLine("has no words for it yet, with the form that keeps it from having them. Generated by")
        appendLine("`DescribeCoverageTest`, which fails when this list changes until it is regenerated and the")
        appendLine("change reviewed.")
        appendSummary(withoutWordsBySpec.flatMap { specAndParts -> specAndParts.second })
        withoutWordsBySpec.forEach { (spec, parts) ->
            appendLine()
            appendLine("## examples/${spec.parentFile.name}/${spec.name}")
            appendLine()
            if (parts.isEmpty()) appendLine("Every part has words.")
            parts.forEach { part -> appendLine("- line ${part.line}, ${part.form}: `${part.writtenAs}`") }
        }
    }

    /** How many parts each form keeps from having words, most first. */
    private fun StringBuilder.appendSummary(parts: List<WithoutWords>) {
        appendLine()
        appendLine("## The forms, most common first")
        appendLine()
        appendLine("| Parts | Form |")
        appendLine("|---|---|")
        parts.groupingBy { part -> part.form }.eachCount().entries
            .sortedWith(compareBy({ formAndCount -> -formAndCount.value }, { formAndCount -> formAndCount.key }))
            .forEach { formAndCount -> appendLine("| ${formAndCount.value} | ${formAndCount.key.replace("|", "\\|")} |") }
        appendLine("| ${parts.size} | in all |")
    }

    @Test
    fun `the declarations describe shows as Velle across the examples are the pinned list`() {
        val current = rendered(exampleSpecs().map { spec -> spec to withoutWords(spec) })
        if (System.getenv("VELLE_UPDATE_WITHOUT_WORDS") == "true") pinned.writeText(current)

        assertEquals(
            pinned.takeIf { file -> file.exists() }?.readText(),
            current,
            "what describe has no words for changed. If a form gained words or an example changed, regenerate " +
                "${pinned.path} with VELLE_UPDATE_WITHOUT_WORDS=true ./gradlew :compiler:test --tests velle.DescribeCoverageTest " +
                "and review the diff",
        )
    }
}
