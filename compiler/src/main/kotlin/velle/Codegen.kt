package velle

/**
 * MockHarness codegen (Reference §22, the milestone scope statement): transpiles a
 * spec to a typed Kotlin surface over the runtime — one typed input value and
 * one `commit` overload per act, one tick function per schedule, one model object (data class) per shape
 * and refinement, the query API over them, and a `main` for driving the
 * system manually.
 * A spike: sugar over VelleSystem, not a standalone compilation.
 */
object Codegen {

    fun generate(specSource: String, systemName: String, packageName: String = "velle.generated"): String {
        val model = Model(Parser.parse(specSource))
        require(model.diagnostics.isEmpty()) { "spec does not resolve: ${model.diagnostics}" }
        return Emitter(model, specSource, systemName, packageName).emit()
    }

    private class Emitter(
        val model: Model,
        val spec: String,
        val name: String,
        val pkg: String,
    ) {
        val sb = StringBuilder()
        fun line(s: String = "") { sb.append(s).append('\n') }

        val schedules: List<String> = model.rules.values
            .flatMap { it.triggers }.filter { it != "commit" }.distinct()

        val domains = DomainAnalysis(model)

        fun emit(): String {
            collectReferenceTypes()
            header()
            line("class ${name}System(startTime: Instant = Instant.parse(\"2026-01-01T09:00:00Z\")) : GeneratedSystem(SPEC, startTime) {")
            line()
            ticks()
            model.exposed.forEach { commitFn(it) }
            model.shapes.keys.forEach { shapeAccessors(it) }
            model.refinements.keys.forEach { refinementAccessors(it) }
            readSurface()
            specConstant()
            line("}")
            line()
            queryAliases()
            actInputTypes()
            closureInputTypes()
            referenceTypes()
            dataClasses()
            viewerInterfaces()
            fieldsClasses()
            mainFn()
            return sb.toString()
        }

        fun header() {
            line("// GENERATED by Velle MockHarness from ${name.lowercase()}.velle — do not edit.")
            line("// Regenerate with: gradle generate")
            line("package $pkg")
            line()
            line("import velle.*")
            line("import java.math.BigDecimal")
            line("import java.time.Instant")
            line("import java.time.LocalDate")
            line()
        }

        fun ticks() {
            if (schedules.isEmpty()) return
            line("    // ── ticks: scheduled events and user acts are both external input ──")
            schedules.forEach { line("    fun tick$it() = system.tick(\"$it\")") }
            line()
        }

        // ── the exposure closure: nested input types (Reference §6, "Inline part
        // creation") — the projection, not the mirror: no `id`, no back-reference
        // (language-populated); an out-of-closure relationship stays a typed view
        // (the reference handle), an in-closure edge is a nested input value. ──

        /** act → its input class: `New<Act>`, the act's stored fields as the
         *  engineer's own type (Reference §22, "External input") */
        val actInputNames: Map<String, String> = model.exposed.associateWith { "New$it" }

        /** structural signature (prop name and owner excluded) plus the fields that may point at a sibling → generated class name */
        val closureNames = linkedMapOf<Pair<ClosureEdge, List<String>>, String>()

        /** The fields of a closure level that may point at a new record elsewhere in [act] (Reference §6; OQ63 §6.2.2). */
        fun siblingsOf(act: String, shape: String, edges: List<ClosureEdge>, backRef: String?): List<StoredProp> =
            model.siblingFields(act, shape, edges, backRef)

        fun closureClassName(edge: ClosureEdge, act: String): String {
            val capable = siblingsOf(act, edge.partShape, edge.children, if (edge.byValue) null else edge.backRef).map { it.name }
            val sig = edge.copy(prop = "", owner = "") to capable
            closureNames[sig]?.let { return it }
            val taken = closureNames.values + actInputNames.values
            var name = "New${edge.partShape}"
            if (name in taken && !edge.byValue)
                name = "New${edge.partShape}Via${edge.backRef.replaceFirstChar { it.uppercase() }}"
            var n = 2
            while (name in taken) name = "New${edge.partShape}${n++}"
            closureNames[sig] = name
            return name
        }

        // ── references supplied by value or in the act (Reference §6; OQ63 §6): a `one`
        // field named in `with`, or one typed by a shape that arrives elsewhere in the act,
        // takes `<Target>Reference`: `Existing(ref)` for a record on the books, `New(value)`
        // for a new one — nested here when the field is named in `with`, placed elsewhere in
        // the act otherwise. A target created by more than one input class, or a union, gets
        // a `New<Target>` interface those classes implement. ──

        fun referenceTypeName(target: String) = "${target}Reference"

        /** The input class a nested value of [operand] under [edge] is: the act's own
         *  input class when it would be identical, else a closure class. */
        fun valueClassName(edge: ClosureEdge, operand: String, act: String): String {
            val children = edge.childrenFor(operand)
            val capable = siblingsOf(act, operand, children, null).map { it.name }
            if (operand in actInputNames && model.closures[operand].orEmpty() == children &&
                siblingsOf(operand, operand, children, null).map { it.name } == capable)
                return actInputNames.getValue(operand)
            return closureClassName(ClosureEdge("", operand, "", children, byValue = true, owner = operand), act)
        }

        /** target → the input classes that create it (anywhere) and the `New` value type its reference takes */
        class ReferenceType(val target: String) {
            val classes = linkedSetOf<String>()
            var valueType: String = ""
            /** The interface the creating classes implement, or null when the single class is the value type. */
            var iface: String? = null
        }
        val referenceTypes = linkedMapOf<String, ReferenceType>()
        /** input class name → the `New<Target>` interfaces it implements */
        val supertypesOf = mutableMapOf<String, MutableSet<String>>()

        /** Name every reference type up front, so act input classes know the interfaces they implement. */
        fun collectReferenceTypes() {
            // per act: the shapes its closure creates and the classes creating each
            for (act in model.exposed) {
                val creators = mutableMapOf<String, MutableSet<String>>()
                val siblingTargets = linkedSetOf<String>()
                fun level(shape: String, edges: List<ClosureEdge>, backRef: String?) {
                    siblingsOf(act, shape, edges, backRef).forEach { siblingTargets.add((it.type as RelType).shape) }
                    for (e in edges) {
                        if (e.byValue) {
                            val r = referenceTypes.getOrPut(e.partShape) { ReferenceType(e.partShape) }
                            for (op in model.basesOf(e.partShape).sorted()) {
                                val c = valueClassName(e, op, act)
                                r.classes.add(c)
                                creators.getOrPut(op) { linkedSetOf() }.add(c)
                                level(op, e.childrenFor(op), null)
                            }
                        } else {
                            val c = closureClassName(e, act)
                            creators.getOrPut(e.partShape) { linkedSetOf() }.add(c)
                            level(e.partShape, e.children, e.backRef)
                        }
                    }
                }
                level(act, model.closures[act].orEmpty(), null)
                for (t in siblingTargets) {
                    val r = referenceTypes.getOrPut(t) { ReferenceType(t) }
                    model.basesOf(t).forEach { op -> creators[op]?.let { r.classes.addAll(it) } }
                }
            }
            for (r in referenceTypes.values) {
                val single = !isUnion(r.target) && r.classes.size == 1
                r.iface = if (single) null else if (isUnion(r.target)) "New${r.target}" else "New${r.target}Value"
                r.valueType = r.iface ?: r.classes.single()
                r.iface?.let { i -> r.classes.forEach { supertypesOf.getOrPut(it) { linkedSetOf() }.add(i) } }
            }
        }

        /** One input value class: the stored fields the committer supplies
         *  (required first, then optional with a `null` default), a reference type
         *  for each `one` field that may take a new record, then one nested list per
         *  part edge. `raw` flattens it to what the runtime takes, `register` puts
         *  its new values in the act's registry, and `asValue` carries it as a
         *  nested value. Shared by the act inputs and the closure part inputs. */
        fun emitInputClass(name: String, act: String, shape: String, stored: List<StoredProp>, edges: List<ClosureEdge>, partsApart: Boolean, backRef: String?) {
            val byValue = edges.filter { it.byValue }
            val parts = edges.filter { !it.byValue }
            val byValueProps = byValue.map { it.prop }.toSet()
            val sibling = siblingsOf(act, shape, edges, backRef)
            val refFields: List<StoredProp> = stored.filter { it.name in byValueProps } + sibling
            val plain = stored.filter { p -> refFields.none { it.name == p.name } }
            // `? initially required` (OQ37-R10): read-optional, but the commit
            // must supply a value — a required, non-null parameter
            val required = plain.filter { it.initially == null && (!isOptional(it.type) || it.initiallyRequired) }
            val optional = plain.filter { it.initially != null || (isOptional(it.type) && !it.initiallyRequired) }
            // every input class is a NewValue; one in a union's `New` interface also implements that
            val unionIfaces = supertypesOf[name].orEmpty()
            val implements = " : " + (unionIfaces + "NewValue").joinToString(", ")
            val ov = if (unionIfaces.isEmpty()) "" else "override "
            fun target(p: StoredProp) = (p.type as RelType).shape
            fun isMany(p: StoredProp) = (p.type as RelType).many
            // a `many` field's elements are each a handle or a new value (Reference §6)
            fun refType(p: StoredProp) =
                if (isMany(p)) "List<${referenceTypeName(target(p))}>" else referenceTypeName(target(p)) + if (isOptional(p.type)) "?" else ""
            fun nestedLine(p: StoredProp) = "(${p.name} as? ${referenceTypeName(target(p))}.New)?.let { put(\"${p.name}\", listOf(it.value.asValue(system, reg))) }"
            val hasParams = required.isNotEmpty() || optional.isNotEmpty() || refFields.isNotEmpty() || parts.isNotEmpty()
            val token = "(reg.tokenOrNull(this)?.let { mapOf(\"${VelleSystem.NEW_KEY}\" to it) } ?: emptyMap())"
            if (!hasParams) {
                line("class $name$implements {")
                line("    override fun raw(system: VelleSystem, reg: NewRegistry): Map<String, Any?> = emptyMap()")
                line("    override fun register(reg: NewRegistry) {}")
                line("    ${ov}fun asValue(system: VelleSystem, reg: NewRegistry): Map<String, Any?> = mapOf(\"${VelleSystem.SHAPE_KEY}\" to \"$shape\") + $token")
                line("}")
                line()
                return
            }
            line("data class $name(")
            required.forEach { line("    val ${it.name}: ${paramType(it.type).removeSuffix("?")},") }
            refFields.filter { !isOptional(it.type) }.forEach { line("    val ${it.name}: ${refType(it)},") }
            optional.forEach { line("    val ${it.name}: ${paramType(it.type).removeSuffix("?")}? = null,") }
            refFields.filter { isOptional(it.type) }.forEach { line("    val ${it.name}: ${refType(it)} = null,") }
            parts.forEach { line("    val ${it.prop}: List<${closureClassName(it, act)}> = emptyList(),") }
            line(")$implements {")
            line("    override fun raw(system: VelleSystem, reg: NewRegistry): Map<String, Any?> = buildMap {")
            required.forEach { line("        put(\"${it.name}\", ${rawExpr(it.name, it.type)})") }
            optional.forEach { line("        ${it.name}?.let { put(\"${it.name}\", ${rawExpr("it", it.type)}) }") }
            refFields.filter { !isMany(it) }.forEach { line("        (${it.name} as? ${referenceTypeName(target(it))}.Existing)?.let { put(\"${it.name}\", system.idOf(it.ref)) }") }
            sibling.filter { !isMany(it) }.forEach { line("        (${it.name} as? ${referenceTypeName(target(it))}.New)?.let { put(\"${it.name}\", NewRef(reg.tokenOf(it.value))) }") }
            sibling.filter { isMany(it) }.forEach { p ->
                val r = referenceTypeName(target(p))
                line("        put(\"${p.name}\", ${p.name}.map { when (it) { is $r.Existing -> system.idOf(it.ref); is $r.New -> NewRef(reg.tokenOf(it.value)) } })")
            }
            if (!partsApart) {
                stored.filter { it.name in byValueProps }.forEach { line("        " + nestedLine(it)) }
                parts.forEach { line("        put(\"${it.prop}\", ${it.prop}.map { it.asValue(system, reg) })") }
            }
            line("    }")
            if (partsApart && edges.isNotEmpty()) {
                // an act's inline parts travel beside its fields (Reference §6,
                // "Inline part creation"); a part's own nested parts ride in its map
                line("    override fun parts(system: VelleSystem, reg: NewRegistry): Map<String, List<Map<String, Any?>>> = buildMap {")
                stored.filter { it.name in byValueProps }.forEach { line("        " + nestedLine(it)) }
                parts.forEach { line("        put(\"${it.prop}\", ${it.prop}.map { it.asValue(system, reg) })") }
                line("    }")
            }
            line("    override fun register(reg: NewRegistry) {")
            stored.filter { it.name in byValueProps }.forEach { line("        (${it.name} as? ${referenceTypeName(target(it))}.New)?.let { reg.add(it.value); it.value.register(reg) }") }
            parts.forEach { line("        ${it.prop}.forEach { reg.add(it); it.register(reg) }") }
            line("    }")
            val partsExpr = if (partsApart && edges.isNotEmpty()) " + parts(system, reg)" else ""
            line("    ${ov}fun asValue(system: VelleSystem, reg: NewRegistry): Map<String, Any?> = raw(system, reg)$partsExpr + (\"${VelleSystem.SHAPE_KEY}\" to \"$shape\") + $token")
            line("}")
            line()
        }

        fun actInputTypes() {
            if (model.exposed.isEmpty()) return
            line("// ── act inputs (Reference §22, \"External input\"): one typed value per act,")
            line("// every stored field the committer supplies and nothing else ──")
            for (shape in model.exposed) {
                val stored = model.shapes.getValue(shape).members.filterIsInstance<StoredProp>()
                emitInputClass(actInputNames.getValue(shape), shape, shape, stored, model.closures[shape].orEmpty(), partsApart = true, backRef = null)
            }
        }

        fun emitClosureClass(name: String, edge: ClosureEdge, act: String) {
            val decl = model.shapes.getValue(edge.partShape)
            val stored = decl.members.filterIsInstance<StoredProp>().filter { edge.byValue || it.name != edge.backRef }
            emitInputClass(name, act, edge.partShape, stored, edge.children, partsApart = false, backRef = if (edge.byValue) null else edge.backRef)
        }

        fun closureInputTypes() {
            val toEmit = linkedMapOf<String, Pair<ClosureEdge, String>>()
            fun visit(edge: ClosureEdge, act: String) {
                edge.children.forEach { visit(it, act) }
                if (edge.byValue) {
                    // one class per operand that is not an act's own input class
                    for (operand in model.basesOf(edge.partShape).sorted()) {
                        val cls = valueClassName(edge, operand, act)
                        if (cls !in actInputNames.values)
                            toEmit.putIfAbsent(cls, ClosureEdge("", operand, "", edge.childrenFor(operand), byValue = true, owner = operand) to act)
                    }
                } else toEmit.putIfAbsent(closureClassName(edge, act), edge to act)
            }
            model.exposed.forEach { shape -> model.closures[shape].orEmpty().forEach { visit(it, shape) } }
            if (toEmit.isEmpty()) return
            line("// ── closure input values (Reference §6, \"Inline part creation\") ──")
            for ((name, e) in toEmit) emitClosureClass(name, e.first, e.second)
        }

        /** The `<Target>Reference` types and the `New<Target>` interfaces (Reference §6; OQ63 §6). */
        fun referenceTypes() {
            if (referenceTypes.isEmpty()) return
            line("// ── references to new records (Reference §6): a `one` field named in `with`, or typed by a shape")
            line("// arriving elsewhere in the act, takes `Existing(ref)`, a record on the books, or `New(value)` ──")
            for (r in referenceTypes.values) {
                r.iface?.let { i ->
                    line("/** A new ${r.target}: one of ${r.classes.joinToString(", ")}. */")
                    line("sealed interface $i {")
                    line("    fun asValue(system: VelleSystem, reg: NewRegistry): Map<String, Any?>")
                    line("    fun register(reg: NewRegistry)")
                    line("}")
                }
                line("sealed interface ${r.target}Reference {")
                line("    /** A ${r.target} already on the books. */")
                line("    data class Existing(val ref: Ref<${r.target}>) : ${r.target}Reference")
                line("    /** A new ${r.target}, created in this commit: nested here when the field is named in `with`, else placed elsewhere in the act. */")
                line("    data class New(val value: ${r.valueType}) : ${r.target}Reference")
                line("}")
                line()
            }
        }

        fun commitFn(shape: String) {
            queueKeyDoc(shape)
            val input = actInputNames.getValue(shape)
            val edges = model.closures[shape].orEmpty()
            // an act declared `by` takes its actor as a parameter beside the input
            // (Reference §22, "The actor"): the committer, never a field of the input
            val actor = model.actorOf(shape)
            val actorParam = actor?.let { ", ${it.name}: Ref<${refBase(it.shape)}>" } ?: ""
            val actorArg = actor?.let { ", ${it.name}" } ?: ""
            val transient = shape in model.transients
            val result = if (transient) "Nothing?" else "Ref<$shape>"
            line("    fun commit(input: $input$actorParam): Commit<$input, $result> =")
            line("        boundary(\"$shape\", input$actorArg).${if (transient) "carryingNoRecord(input)" else "carrying(input)"}")
            line()
        }

        /** The reference type a value typed by [shape] is: a refinement's base shape (an actor
         *  declared `by Administrator` is a `Ref<Staff>`), a union or base shape itself. */
        fun refBase(shape: String): String = model.baseOf(shape) ?: shape

        /** The serialization contract (OQ40): the queue keys this commit's work
         *  joins, stated on the generated surface so the engineer reads them
         *  off the contract instead of re-deriving them from the rule graph. */
        fun queueKeyDoc(shape: String) {
            val domain = domains.actDomains[shape] ?: return
            val keys = domain.renderKeys(shape.replaceFirstChar { it.lowercase() })
            line("    /** ${queueKeyLead(domain, keys)}")
            for (w in domain.widenings) {
                val status = if (w.tolerated) "tolerated by ${w.declaration}" else "unexamined (A5)"
                line("     *  System-wide over ${w.shape} — ${w.cause} ($status).")
            }
            line("     *  Commits sharing a queue key are handled one at a time, in arrival")
            line("     *  order (U3); commits whose keys are disjoint run in parallel. */")
        }

        fun queueKeyLead(domain: SerializationDomain, keys: List<String>): String = when {
            domain.wide && keys.isEmpty() -> "Queue: system-wide."
            domain.wide -> "Queue keys: ${keys.joinToString(", ") { "[$it]" }} — plus system-wide width below."
            keys.isEmpty() -> "Queue keys: none — this commit contends with no other work."
            else -> "Queue ${if (keys.size == 1) "key" else "keys"}: ${keys.joinToString(", ") { "[$it]" }}."
        }

        // ── the surface (Reference §22): model objects in, model objects out ─────
        // The spec declares definitions; the caller composes queries. What an
        // engineer holds is a model object — the shape's data class, every field
        // read once at the moment of the read — and a model object is itself a
        // `Ref<T>` to its record, so it passes wherever a reference is taken. A
        // reference field holds a `Ref<T>`; `read(ref)` resolves it. Nothing is
        // read *through* a reference.

        /** The roots a query may name: every readable shape and refinement, static unions included (Reference §9). */
        val queryRoots: List<String> =
            model.shapes.keys.filterNot { it in model.transients } +
                model.refinements.keys.filter { r ->
                    model.viewScopeOf(r) != null && model.basesOf(r).none { it in model.transients }
                }

        fun isRoot(name: String) = name in queryRoots
        fun isUnion(name: String) = name in model.refinements && model.isStaticUnion(name)
        /** The static unions a shape is an operand of. */
        fun unionsOf(shape: String): List<String> = model.refinements.keys.filter { isUnion(it) && shape in model.basesOf(it) }
        /** The reference type a model object of [root] is: its base shape, or the union it is drawn from. */
        fun refTarget(root: String): String = model.baseOf(root) ?: model.unionRootOf(root) ?: root

        /** The members a model object carries and a fields class exposes: everything but `id`. */
        fun dataMembers(scope: String): List<Pair<String, MemberInfo>> =
            model.membersOf(scope).entries.filter { it.key != "id" }.map { it.key to it.value }

        /** A union's own derived members, carried by each operand's model object (read in the union's scope). */
        fun unionMembers(shape: String): List<Triple<String, String, VType>> =
            unionsOf(shape).flatMap { u ->
                model.refinements.getValue(u).members.filterIsInstance<DerivedProp>().map { Triple(it.name, u, model.typeOf(it.type)) }
            }

        /** The refinements a model object of [root] carries a membership flag for. */
        fun membershipsOf(root: String): List<String> {
            val members = model.membersOf(root).keys + unionMembers(root).map { it.first }
            val over: (String) -> Boolean = when {
                isUnion(root) -> { r -> model.isCrossBase(r) && model.unionRootOf(r) == root }
                root in model.shapes -> { r -> model.baseOf(r) == root || (model.isCrossBase(r) && model.unionRootOf(r) in unionsOf(root)) }
                else -> { r -> model.baseOf(r) == model.baseOf(root) }
            }
            // a member already named `isX` keeps its name; the flag yields
            return model.refinements.keys.filter { r -> isRoot(r) && r != root && !isUnion(r) && over(r) && "is$r" !in members }
        }

        // ── visibility (Reference §22, "The actor"; OQ33 §5.7–§5.10, §6.1) ──────
        // One class per shape, declaring each field once; one interface per viewer
        // shape that a clause names, listing what that viewer may see. A field
        // with a clause is nullable in the class — for some viewer it is absent —
        // and appears in a viewer's interface only when some clause admits that
        // viewer's shape, nullable there since membership and predicates are
        // runtime facts. The engineer's own read returns the class, unfiltered.

        val viewerShapes: List<String> = model.viewerShapes.toList().sorted()
        fun gated(m: MemberInfo) = m.visible.isNotEmpty()
        fun hasGated(root: String) = !isUnion(root) && dataMembers(root).any { gated(it.second) }
        fun admits(c: VisibleClause, viewer: String) = c.anyone || viewer in model.basesOf(c.shape!!)
        fun fieldShown(m: MemberInfo, viewer: String) = m.visible.isEmpty() || m.visible.any { admits(it, viewer) }
        /** Can a record of [root] ever be returned to a viewer of [viewer]'s shape? */
        fun recordShown(root: String, viewer: String): Boolean {
            if (isUnion(root)) return model.basesOf(root).any { recordShown(it, viewer) }
            val cs = model.recordVisibility(root)
            return cs.isEmpty() || cs.any { admits(it, viewer) }
        }
        /** The type a viewer of [viewer]'s shape receives for [root]: its interface when fields are gated, else the class. */
        fun viewType(root: String, viewer: String) = if (hasGated(root)) "${root}For$viewer" else root
        /** The class's type for a member: nullable when a clause can hide it. */
        fun fieldType(m: MemberInfo): String = kotlinType(m.type).let { if (gated(m) && !it.endsWith("?")) "$it?" else it }
        /** A union's member is nullable when any operand gates it. */
        fun unionFieldType(union: String, name: String, t: VType): String =
            kotlinType(t).let { k -> if (!k.endsWith("?") && model.basesOf(union).any { b -> model.membersOf(b)[name]?.let(::gated) == true }) "$k?" else k }
        fun viewersOf(root: String): List<String> = viewerShapes.filter { recordShown(root, it) }

        // ── accessors: the degenerate query — every instance, as model objects ──
        fun shapeAccessors(shape: String) {
            if (shape in model.transients) return // an input to the state, never readable after its commit
            line("    fun ${plural(shape)}(): List<$shape> = all(\"$shape\") { materialize$shape(it) }")
        }

        fun refinementAccessors(ref: String) {
            if (!isRoot(ref)) return
            line("    fun ${plural(ref)}(): List<$ref> = all(\"$ref\") { materialize$ref(it) }")
        }

        fun readSurface() {
            line()
            line("    // ── the query API: `read(ref)`, `read.<root>.where { }.orderBy { }.page(n).list()` (Reference §22) ──")
            line("    val read = Read()")
            line()
            line("    inner class Read : ReadSurface<Read>(system, { materialize(it) }) {")
            queryRoots.forEach { root ->
                line()
                line("        val ${plural(root)}: ${root}Query get() = query(\"$root\", ${root}Fields()) { materialize$root(it) }")
                when {
                    root in model.shapes -> {
                        line("        /** Fetch by store key (a model object is not a key: resolve it with `read(it)`). */")
                        line("        fun ${decap(root)}(key: StoreKey): $root = byKey(\"$root\", key)")
                        line("        fun ${decap(root)}(key: Long): $root = ${decap(root)}(StoreKey(key))")
                    }
                    !isUnion(root) -> {
                        line("        /** The record behind [ref] as a member of $root, or null when it is not one. */")
                        line("        fun ${decap(root)}(ref: Ref<${refTarget(root)}>): $root? = member(\"$root\", ref) { materialize$root(it) }")
                    }
                }
            }
            line("    }")
            line()
            line("    /** The model object of whatever shape the instance is (a union-typed reference resolves to its operand's). */")
            line("    private fun materialize(id: Long): Ref<*> = when (val shape = system.shapeOf(id)) {")
            model.shapes.keys.filterNot { it in model.transients }.forEach { line("        \"$it\" -> materialize$it(id)") }
            line("        else -> throw IllegalStateException(\"no model object for '\$shape'\")")
            line("    }")
            queryRoots.forEach { root -> materializer(root) }
            viewerShapes.forEach { v -> viewerReadSurface(v) }
        }

        /** One name per typed query, so `read.orders` reads as an `OrderQuery` and a viewer's as an `OrderQueryForStaff`. */
        fun queryAliases() {
            line("// ── the typed queries: one name per root, and per root a viewer sees with fields gated ──")
            queryRoots.forEach { root -> line("typealias ${root}Query = TypedQuery<${root}Fields, $root>") }
            viewerShapes.forEach { v ->
                queryRoots.filter { recordShown(it, v) && hasGated(it) }.forEach { root ->
                    line("typealias ${root}QueryFor$v = TypedQuery<${root}Fields, ${root}For$v>")
                }
            }
            line()
        }

        /** The read surface for a viewer of shape [v] (Reference §22, "The actor"): the same
         *  roots, each query carrying the viewer so the engine admits only what the shape's
         *  clauses admit, each fetch resolving absent for an invisible record, each model
         *  object projected to the viewer's interface where fields are gated. A root no
         *  clause ever shows to this viewer's shape is not on the surface at all. */
        fun viewerReadSurface(v: String) {
            val roots = queryRoots.filter { recordShown(it, v) }
            line()
            line("    // ── reads for a $v: what the surface returns to one of them (Reference §22, \"The actor\") ──")
            line("    fun read(viewer: Ref<$v>): ${v}Read = ${v}Read(viewer)")
            line()
            line("    inner class ${v}Read(viewer: Ref<$v>) : ViewerReadSurface(system, viewer) {")
            for (root in roots) {
                val view = viewType(root, v)
                val query = if (hasGated(root)) "${root}QueryFor$v" else "${root}Query"
                val mat = if (hasGated(root)) "materialize${root}For$v(system.idOf(viewer), it)" else "materialize$root(it)"
                line("        val ${plural(root)}: $query get() = query(\"$root\", ${root}Fields()) { $mat }")
                when {
                    root in model.shapes -> {
                        line("        /** The record behind [ref], or null when it is gone or not shown to this viewer. */")
                        line("        fun ${decap(root)}(ref: Ref<$root>): $view? = shown(\"$root\", ref) { $mat }")
                        line("        fun ${decap(root)}(key: StoreKey): $view? = ${decap(root)}(Ref.Persisted(\"$root\", key))")
                        line("        fun ${decap(root)}(key: Long): $view? = ${decap(root)}(StoreKey(key))")
                    }
                    !isUnion(root) -> {
                        line("        /** The record behind [ref] as a member of $root, or null when it is not one or not shown to this viewer. */")
                        line("        fun ${decap(root)}(ref: Ref<${refTarget(root)}>): $view? = shown(\"$root\", ref) { $mat }")
                    }
                }
            }
            line("    }")
            for (root in roots.filter { hasGated(it) }) viewerMaterializer(root, v)
        }

        /** A model object projected for a viewer: the class, its hidden fields absent (null). */
        fun viewerMaterializer(root: String, v: String) {
            val own = model.refinements[root]?.members?.filterIsInstance<DerivedProp>()?.map { it.name }?.toSet().orEmpty()
            line()
            line("    private fun materialize${root}For$v(viewer: Long, id: Long): ${root}For$v {")
            line("        val hidden = system.hiddenFields(viewer, id, \"$root\")")
            line("        return $root(")
            line("            key = system.refFor(id).key,")
            for ((name, m) in dataMembers(root)) {
                val call = if (name in own) "system.getAs(id, \"$root\", \"$name\")" else "system.get(id, \"$name\")"
                val read = readExpr(call, m.type)
                line("            $name = ${if (gated(m)) "if (\"$name\" in hidden) null else $read" else read},")
            }
            if (root in model.shapes) unionMembers(root).forEach { (name, u, t) ->
                line("            $name = ${readExpr("system.getAs(id, \"$u\", \"$name\")", t)},")
            }
            membershipsOf(root).forEach { r -> line("            is$r = system.isMember(id, \"$r\"),") }
            line("        )")
            line("    }")
        }

        /** One interface per viewer shape per root with gated fields (Reference §22, "The actor"; OQ33 §6.1). */
        fun viewerInterfaces() {
            val pairs = queryRoots.filter { hasGated(it) }.flatMap { root -> viewersOf(root).map { root to it } }
            if (pairs.isEmpty()) return
            line()
            line("// ── what a viewer receives (Reference §22, \"The actor\"): one interface per viewer shape per shape")
            line("// with gated fields — the fields that viewer may see, a gated one nullable, the rest as the class ──")
            for ((root, v) in pairs) {
                line()
                line("interface ${root}For$v : Keyed {")
                for ((name, m) in dataMembers(root)) {
                    if (!fieldShown(m, v)) continue
                    line("    val $name: ${fieldType(m)}")
                }
                if (root in model.shapes) unionMembers(root).forEach { (name, _, t) -> line("    val $name: ${kotlinType(t)}") }
                membershipsOf(root).forEach { r -> line("    val is$r: Boolean") }
                line("}")
            }
        }

        /** The model object from a handle: every member read at the moment of the read (R5). */
        fun materializer(root: String) {
            line()
            if (isUnion(root)) {
                line("    private fun materialize$root(id: Long): $root = materialize(id) as $root")
                return
            }
            val own = model.refinements[root]?.members?.filterIsInstance<DerivedProp>()?.map { it.name }?.toSet().orEmpty()
            line("    private fun materialize$root(id: Long): $root = $root(")
            line("        key = system.refFor(id).key,")
            for ((name, m) in dataMembers(root)) {
                val call = if (name in own) "system.getAs(id, \"$root\", \"$name\")" else "system.get(id, \"$name\")"
                line("        $name = ${readExpr(call, m.type)},")
            }
            if (root in model.shapes) unionMembers(root).forEach { (name, u, t) ->
                line("        $name = ${readExpr("system.getAs(id, \"$u\", \"$name\")", t)},")
            }
            membershipsOf(root).forEach { r -> line("        is$r = system.isMember(id, \"$r\"),") }
            line("    )")
        }

        fun dataClasses() {
            line()
            line("// ── the shapes as model objects: what a read returns (Reference §22; OQ51 R5) ──")
            line("// A model object is a reference to its own record (`Ref<T>`): equality is identity,")
            line("// a reference field is a `Ref<T>` to resolve with `read(ref)`, a membership flag is")
            line("// the record's membership at the moment of the read.")
            for (root in queryRoots) {
                line()
                if (isUnion(root)) { unionInterface(root); continue }
                val target = refTarget(root)
                val unionNames = if (root in model.shapes) unionsOf(root) else emptyList()
                val inherited = unionNames.flatMap { model.membersOf(it).keys + membershipsOf(it).map { r -> "is$r" } }.toSet()
                // the viewer interfaces this class implements: one per viewer shape a record of it can be shown to
                val viewerIfaces = if (hasGated(root)) viewersOf(root).map { "${root}For$it" } else emptyList()
                val viewerMembers = if (hasGated(root)) viewersOf(root).flatMap { v -> dataMembers(root).filter { fieldShown(it.second, v) }.map { it.first } }.toSet() else emptySet()
                val supertypes = listOf("Ref<$target>") + unionNames + viewerIfaces
                line("data class $root(")
                line("    override val key: StoreKey,")
                for ((name, m) in dataMembers(root)) line("    ${if (name in inherited || name in viewerMembers) "override " else ""}val $name: ${fieldType(m)},")
                if (root in model.shapes) unionMembers(root).forEach { (name, _, t) -> line("    override val $name: ${kotlinType(t)},") }
                membershipsOf(root).forEach { r ->
                    line("    /** membership of $r at the moment of the read */")
                    line("    ${if ("is$r" in inherited || viewerIfaces.isNotEmpty()) "override " else ""}val is$r: Boolean,")
                }
                line(") : ${supertypes.joinToString(", ")} {")
                line("    override val shape: String get() = \"$target\"")
                line("    override fun equals(other: Any?) = other is Keyed && other.shape == shape && other.key == key")
                line("    override fun hashCode() = 31 * shape.hashCode() + key.hashCode()")
                line("}")
            }
        }

        /** A static union (Reference §9) as an interface its operands' model objects implement:
         *  the shared members, the union's own derived members, and its membership flags.
         *  Covariance makes a `Ref<Post>` a `Ref<Content>`, which is how an operand widens. */
        fun unionInterface(union: String) {
            line("interface $union : Keyed {")
            line("    /** this record as a reference typed by the union, for a parameter that takes one */")
            line("    val ref: Ref<$union> get() = Ref.Persisted(shape, key)")
            for ((name, m) in dataMembers(union)) line("    val $name: ${unionFieldType(union, name, m.type)}")
            membershipsOf(union).forEach { r -> line("    val is$r: Boolean") }
            line("}")
        }

        fun fieldsClasses() {
            line()
            line("// ── the builder's vocabulary: one field handle per member, memberships per refinement ──")
            for (root in queryRoots) {
                line()
                line("class ${root}Fields(path: List<String> = emptyList()) : Fields(path) {")
                for ((memberName, m) in dataMembers(root)) {
                    val handle = fieldHandle(m.type) ?: continue
                    line("    val $memberName: $handle get() = ${fieldHandleCtor(m.type, memberName)}")
                }
                if (root in model.shapes) unionMembers(root).forEach { (name, _, t) ->
                    fieldHandle(t)?.let { line("    val $name: $it get() = ${fieldHandleCtor(t, name)}") }
                }
                // memberships of every refinement over this root (`isOverdueInvoice()`)
                membershipsOf(root).forEach { r -> line("    fun is$r(): Expr = isA(\"$r\")") }
                line("}")
            }
        }

        /** The field-handle class for a member's type; null for members the builder does not filter on (collections). */
        fun fieldHandle(t: VType): String? = when (t) {
            is VType.Num -> "NumField"
            // an extension type (Reference §5): ordered comparisons only when the type declares an ordering
            is VType.Ext -> model.registry[t.qualifiedName]?.let { x ->
                (if (x.ordering != null) "OrderedExtField" else "ExtField") + "<${x.kotlinClass.qualifiedName}>"
            }
            VType.Text -> "TextField"
            VType.Bool -> "BoolField"
            VType.DateT -> "DateField"
            VType.DateTimeT -> "DateTimeField"
            is VType.Inst -> if (isRoot(t.shape)) "${t.shape}Fields" else "RefField"
            is VType.Optional -> fieldHandle(t.inner)
            else -> null
        }

        /** The expression constructing a member's field handle; an extension type's names the type. */
        fun fieldHandleCtor(t: VType, name: String): String {
            val bare = (t as? VType.Optional)?.inner ?: t
            val handle = fieldHandle(t)!!
            return if (bare is VType.Ext) "$handle(fieldPath + \"$name\", \"${bare.qualifiedName}\")" else "$handle(fieldPath + \"$name\")"
        }

        fun specConstant() {
            line()
            line("    companion object {")
            line("        private val SPEC = \"\"\"")
            spec.trimEnd().lines().forEach { line(it) }
            line("\"\"\"")
            line("    }")
        }

        fun mainFn() {
            line()
            line("fun main() {")
            line("    val sys = ${name}System()")
            line("    println(\"Velle MockHarness — $name\")")
            line("    println(\"Commits: ${model.exposed.joinToString(", ") { a -> "commit(New$a(...)" + (model.actorOf(a)?.let { ", ${it.name}" } ?: "") + ")" }}\")")
            if (schedules.isNotEmpty())
                line("    println(\"Ticks: ${schedules.joinToString(", ") { "tick$it()" }}\")")
            line("    println(\"Edit this main to drive the system; state prints below.\")")
            line()
            line("    // <your scenario here>")
            line()
            model.shapes.keys.filterNot { it in model.transients }.forEach {
                line("    println(\"$it: \" + sys.${plural(it)}().size)")
            }
            line("}")
        }

        // ── type mapping ─────────────────────────────────────────────────────

        fun isOptional(t: TypeRef) = (t as? ScalarType)?.optional == true || (t as? RelType)?.optional == true

        /** Parameter type for a commit function (relationships take references — a model object is one; `many` takes lists). */
        fun paramType(t: TypeRef): String = when (t) {
            is RelType ->
                if (t.many) "List<Ref<${t.shape}>>"
                else "Ref<${t.shape}>" + if (t.optional) "?" else ""
            is ScalarType ->
                if (t.many) "List<${scalarKotlin(t.name)}>"
                else scalarKotlin(t.name) + if (t.optional) "?" else ""
        }

        /** Convert a parameter back to the raw value the runtime accepts. */
        fun rawExpr(expr: String, t: TypeRef): String = when (t) {
            is RelType -> if (t.many) "$expr.map { system.idOf(it) }" else "system.idOf($expr)"
            is ScalarType -> expr
        }

        fun scalarKotlin(name: String): String = when (name) {
            "text" -> "String"
            "integer" -> "Int"
            "long" -> "Long"
            "decimal" -> "BigDecimal"
            "double" -> "Double"
            "boolean" -> "Boolean"
            "Date" -> "LocalDate"
            "DateTime" -> "Instant"
            // a registered extension type: its own class, fully qualified (Reference §5; OQ65)
            else -> model.typeScope[name]?.kotlinClass?.qualifiedName ?: "Any"
        }

        fun kotlinType(t: VType): String = when (t) {
            is VType.Num -> scalarKotlin(t.name)
            is VType.Ext -> model.registry[t.qualifiedName]?.kotlinClass?.qualifiedName ?: "Any"
            VType.Text -> "String"
            VType.Bool -> "Boolean"
            VType.DateT -> "LocalDate"
            VType.DateTimeT -> "Instant"
            is VType.Inst -> "Ref<${refBase(t.shape)}>"
            is VType.Coll -> "List<Ref<${t.shape}>>"
            is VType.CollS -> "List<${scalarKotlin(t.name)}>"
            is VType.Optional -> kotlinType(t.inner) + "?"
            VType.Id, VType.Unknown -> "Any"
        }

        /** Expression converting a raw runtime read into the typed surface. */
        fun readExpr(call: String, t: VType): String = when (t) {
            is VType.Num -> when (t.name) {
                "integer" -> "($call as BigDecimal).intValueExact()"
                "long" -> "($call as BigDecimal).longValueExact()"
                "double" -> "($call as BigDecimal).toDouble()"
                else -> "$call as BigDecimal"
            }
            VType.Text -> "$call as String"
            VType.Bool -> "$call as Boolean"
            VType.DateT -> "$call as LocalDate"
            VType.DateTimeT -> "$call as Instant"
            is VType.Ext -> "$call as ${kotlinType(t)}"
            is VType.Inst -> "system.refFor($call as Long)"
            is VType.Coll -> "($call as List<*>).map { system.refFor(it as Long) }"
            is VType.CollS -> when (t.name) {
                "integer" -> "($call as List<*>).map { (it as BigDecimal).intValueExact() }"
                "long" -> "($call as List<*>).map { (it as BigDecimal).longValueExact() }"
                "double" -> "($call as List<*>).map { (it as BigDecimal).toDouble() }"
                "decimal" -> "($call as List<*>).map { it as BigDecimal }"
                else -> "($call as List<*>).map { it as ${scalarKotlin(t.name)} }"
            }
            is VType.Optional -> when (val inner = t.inner) {
                is VType.Inst -> "($call as Long?)?.let { system.refFor(it) }"
                else -> "$call as ${kotlinType(t)}"
            }
            VType.Id, VType.Unknown -> call
        }

        fun decap(s: String) = s.replaceFirstChar { it.lowercase() }
        fun plural(s: String) = decap(s) + "s"
    }
